export const ALL_MOOD_LIST: MoodInfo[] = Object.values(MOODS);

export function getSongsForMood(moodId: MoodType): Song[] {
  return MOOD_SONGS[moodId] || [];
}

export function getRandomMood(currentMood?: MoodType): MoodType {
  const moodKeys = Object.keys(MOODS) as MoodType[];
  const pool = currentMood ? moodKeys.filter((m) => m !== currentMood) : moodKeys;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
